// Compile the ACTUAL controlled LABS design tokens/styles and project taxonomy.
// No fork of BRAIN: this generates UI-only assets from the same LABS sources on each private OS release.
import {readFileSync,writeFileSync} from "node:fs";
import {createHash} from "node:crypto";
import {build} from "esbuild";
const files=[
"src/pages/labs/labs.css",
"src/pages/labs/labsGold.css",
"src/pages/labs/labsV4.css",
"src/pages/labs/labsV4Root.css",
"src/pages/labs/labsMobileFix.css",
"src/pages/labs/labsIndex.css",
"src/pages/labs/labsProjectPulse.css"
];
const css=files.map(path=>readFileSync(path,"utf8")).join("\n");
const sha=createHash("sha256").update(css).digest("hex");
const out=await build({entryPoints:["src/pages/labs/labsCurrentProjection.ts"],bundle:true,platform:"node",format:"esm",write:false,logLevel:"silent"});
const projection=await import("data:text/javascript;base64,"+Buffer.from(out.outputFiles[0].text).toString("base64"));
const catalog=projection.projects.filter(x=>x.universe==="4PLANET").map(x=>({
 slug:x.slug,title:x.title,kind:x.kind,parent:x.parent||"",
 projectClass:x.projectClass||"",accent:x.accent,summary:x.summary||""
}));
if(!css.includes(".labs-project-box")||!css.includes(".labs-universe-head")||!css.includes("--accent-ocean:#19baff")||catalog.length<25)
 throw Error("EXACT_LABS_SOURCE_ASSETS_UNAVAILABLE");
const dest="ops/labs-domain-adapter/src/founder-labs-assets.js";
writeFileSync(dest,"// AUTOGENERATED FROM THE REAL LABS CSS + CURRENT CONTROLLED PUBLIC-SAFE PROJECT TAXONOMY. DO NOT HAND-EDIT.\n"+
 "export const LABS_CSS="+JSON.stringify(css)+";\n"+
 "export const LABS_CSS_SHA="+JSON.stringify(sha)+";\n"+
 "export const LABS_CATALOG="+JSON.stringify(catalog)+";\n");
console.log("EXACT_LABS_SOURCE_CSS_SHA256="+sha+" stylesheets="+files.length+" 4PLANET catalog entries="+catalog.length+" (public-safe historical hierarchy only; NO CURRENT STATUS imported)");
